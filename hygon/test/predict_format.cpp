static inline bool eval_cond(const RuleCond &c, const double feats[FEAT_COUNT])
{
    const double v = feats[(int)c.feat];
    return c.is_le ? (v <= c.cut) : (v > c.cut);
}

static inline PredClass classify_with_rule_votes(const double feats[FEAT_COUNT])
{
    double scores[PRED_CLASS_COUNT] = {0.0};
    bool matched_any = false;

    for (size_t ri = 0; ri < sizeof(kRules) / sizeof(kRules[0]); ++ri)
    {
        const Rule &r = kRules[ri];
        bool ok = true;
        for (uint8_t k = 0; k < r.cond_count; ++k)
        {
            const RuleCond &c = kConds[(size_t)r.cond_start + k];
            if (!eval_cond(c, feats))
            {
                ok = false;
                break;
            }
        }
        if (ok)
        {
            matched_any = true;
            scores[(int)r.clazz] += (double)r.weight;
        }
    }

    // Default class from smat_8.rules: SELL_16_0
    if (!matched_any)
        return PRED_SELL_16_0;

    PredClass best = PRED_SELL_16_0;
    double best_score = scores[(int)best];

    for (int c = 0; c < (int)PRED_CLASS_COUNT; ++c)
    {
        if (scores[c] > best_score)
        {
            best_score = scores[c];
            best = (PredClass)c;
        }
    }
    return best;
}

static inline alphasparseFormat_t predclass_to_format(PredClass pc, int *best_C, int *best_sigma)
{
    if (best_C)
        *best_C = 16;
    if (best_sigma)
        *best_sigma = 0;

    switch (pc)
    {
    case PRED_CSR:
        return ALPHA_SPARSE_FORMAT_CSR;
    case PRED_COO:
        return ALPHA_SPARSE_FORMAT_COO;
    case PRED_DIA:
        return ALPHA_SPARSE_FORMAT_DIA;
    case PRED_SELL_16_0:
        if (best_C)
            *best_C = 16;
        if (best_sigma)
            *best_sigma = 0;
        return ALPHA_SPARSE_FORMAT_SELL_C_SIGMA;
    case PRED_SELL_16_1024:
        if (best_C)
            *best_C = 16;
        if (best_sigma)
            *best_sigma = 1024;
        return ALPHA_SPARSE_FORMAT_SELL_C_SIGMA;
    case PRED_SELL_8_0:
        if (best_C)
            *best_C = 8;
        if (best_sigma)
            *best_sigma = 0;
        return ALPHA_SPARSE_FORMAT_SELL_C_SIGMA;
    case PRED_SELL_8_1024:
        if (best_C)
            *best_C = 8;
        if (best_sigma)
            *best_sigma = 1024;
        return ALPHA_SPARSE_FORMAT_SELL_C_SIGMA;
    default:
        return ALPHA_SPARSE_FORMAT_CSR;
    }
}

alphasparseFormat_t predict_best_format_from_coo(const internal_spmat mat, int *best_C, int *best_sigma)
{
    if (mat == nullptr)
        return ALPHA_SPARSE_FORMAT_CSR;

    const int64_t rows = mat->rows;
    const int64_t cols = mat->cols;
    const int64_t nnz = mat->nnz;
    const ALPHA_INT *row_data = mat->row_data;
    const ALPHA_INT *col_data = mat->col_data;

    if (rows <= 0 || cols <= 0 || nnz <= 0 || row_data == nullptr || col_data == nullptr)
        return ALPHA_SPARSE_FORMAT_CSR;

    // -----------------------------
    // 8 features used by smat_8.{names,rules}
    // -----------------------------
    std::vector<int64_t> row_cnt((size_t)rows, 0);
    std::vector<int64_t> col_cnt((size_t)cols, 0);
    std::vector<std::vector<ALPHA_INT>> row_cols((size_t)rows);

    for (int64_t i = 0; i < nnz; ++i)
    {
        const int64_t r = (int64_t)row_data[i];
        const int64_t c = (int64_t)col_data[i];
        if ((uint64_t)r < (uint64_t)rows)
        {
            row_cnt[(size_t)r]++;
            row_cols[(size_t)r].push_back((ALPHA_INT)c);
        }
        if ((uint64_t)c < (uint64_t)cols)
        {
            col_cnt[(size_t)c]++;
        }
    }

    // Row nnz gini + ratio(row_nnz<=16)
    std::vector<double> row_nnz_vec;
    row_nnz_vec.reserve((size_t)rows);
    int64_t le16 = 0;
    for (int64_t r = 0; r < rows; ++r)
    {
        const int64_t v = row_cnt[(size_t)r];
        row_nnz_vec.push_back((double)v);
        if (v <= 16)
            ++le16;
    }
    const double row_nnz_gini = gini(row_nnz_vec);
    const double row_nnz_ratio_le_16 = safe_div((double)le16, (double)rows);

    // Column nnz CV
    std::vector<double> col_nnz_vec;
    col_nnz_vec.reserve((size_t)cols);
    for (int64_t c = 0; c < cols; ++c)
        col_nnz_vec.push_back((double)col_cnt[(size_t)c]);
    const double col_nnz_mean = mean(col_nnz_vec);
    const double col_nnz_std = stddev_pop(col_nnz_vec, col_nnz_mean);
    const double col_nnz_cv = safe_div(col_nnz_std, col_nnz_mean);

    // Bandwidth ratio + adjacent nnz ratio
    int64_t bw_max = 0; // max |col-row|
    int64_t adjacent_pairs = 0;

    for (int64_t r = 0; r < rows; ++r)
    {
        auto &v = row_cols[(size_t)r];
        if (v.empty())
            continue;

        std::sort(v.begin(), v.end());
        v.erase(std::unique(v.begin(), v.end()), v.end());

        for (size_t k = 0; k < v.size(); ++k)
        {
            const int64_t c = (int64_t)v[k];
            const int64_t d = std::llabs(c - r);
            if (d > bw_max)
                bw_max = d;

            if (k > 0 && ((int64_t)v[k] - (int64_t)v[k - 1] == 1))
                adjacent_pairs++;
        }
    }

    const double bandwidth_ratio = safe_div((double)(bw_max + 1), (double)cols);
    const double adjacent_nnz_ratio = safe_div((double)adjacent_pairs, (double)nnz);

    double feats[FEAT_COUNT] = {0.0};
    feats[FEAT_ROWS] = (double)rows;
    feats[FEAT_COLS] = (double)cols;
    feats[FEAT_NNZ] = (double)nnz;
    feats[FEAT_ROW_NNZ_GINI] = row_nnz_gini;
    feats[FEAT_ROW_NNZ_RATIO_LE_16] = row_nnz_ratio_le_16;
    feats[FEAT_COL_NNZ_CV] = col_nnz_cv;
    feats[FEAT_BANDWIDTH_RATIO] = bandwidth_ratio;
    feats[FEAT_ADJACENT_NNZ_RATIO] = adjacent_nnz_ratio;

    const PredClass pc = classify_with_rule_votes(feats);
    return predclass_to_format(pc, best_C, best_sigma);
}
